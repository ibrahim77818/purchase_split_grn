# -*- coding: utf-8 -*-
from odoo import fields, models


class ResCompany(models.Model):
    _inherit = 'res.company'

    split_grn_enabled = fields.Boolean(
        string='Split Receipts', default=False,
        help='Split the receipts generated by confirmed purchase orders '
             'according to the selected criteria.')
    split_grn_by_date = fields.Boolean(
        string='Split by Delivery Date', default=False,
        help='Create one receipt per expected arrival date of the purchase order lines.')
    split_grn_by_location = fields.Boolean(
        string='Split by Destination Location', default=False,
        help='Create one receipt per destination location of the purchase order lines.')
    split_grn_by_warehouse = fields.Boolean(
        string='Split by Warehouse', default=False,
        help='Let purchase order lines be received in other warehouses of the same company, '
             'with one receipt per warehouse using its own receipt operation.')
